#!/usr/bin/env node
/**
 * Keeps skills/lady-lens/SKILL.md in step with the MCP tools lady-lens offers: the part between the markers is
 * generated from buildMcpToolSchemas(); the workflow above it stays hand-written.
 *   npm run skill   rewrite the generated part (also runs in `npm run build`)
 * test/skillTools.internal.test.js fails when the file is stale, so `npm run check` catches a new tool without a skill update.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { buildMcpToolSchemas } from '../core/mcp/index.js';

export const SKILL_FILE = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'skills', 'lady-lens', 'SKILL.md');
const BEGIN = '<!-- tools:begin (generated by scripts/update-skill.mjs; edit the tool descriptions, not this list) -->';
const END = '<!-- tools:end -->';

const oneLine = (text) => String(text ?? '').replace(/\s+/g, ' ').trim();

/** The generated tool list: one line per MCP tool, with its whole description and its parameters (required ones first; the optional `repo` of every tool left out). */
export function renderToolList(schemas = buildMcpToolSchemas()) {
    const lines = schemas.map(({ name, description, parameters, inputSchema }) => {
        const schema = parameters ?? inputSchema ?? {};
        const required = new Set(schema.required ?? []);
        const params = Object.keys(schema.properties ?? {}).filter(key => key !== 'repo' || required.has(key))
            .sort((a, b) => Number(required.has(b)) - Number(required.has(a)))
            .map(key => (required.has(key) ? key : `${key}?`));
        return `- \`${name}(${params.join(', ')})\`: ${oneLine(description)}`;
    });
    return [BEGIN, '## Tools', '', ...lines, END].join('\n');
}

/** The skill with its generated part replaced (appended when the markers are missing). */
export function updateSkill(text, list = renderToolList()) {
    const start = text.indexOf(BEGIN), end = text.indexOf(END);
    if (start < 0 || end < start) return `${text.trimEnd()}\n\n${list}\n`;
    return `${text.slice(0, start)}${list}${text.slice(end + END.length)}`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const before = fs.readFileSync(SKILL_FILE, 'utf8');
    const after = updateSkill(before);
    if (after !== before) fs.writeFileSync(SKILL_FILE, after);
    console.log(after === before ? 'SKILL.md is current' : `SKILL.md updated (${buildMcpToolSchemas().length} tools)`);
}
